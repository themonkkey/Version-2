def build() -> str:
    s = PAGE.read_text()
    a = s.index("<style>") + len("<style>")
    b = s.index("</style>", a)
    css = s[a:b]
    # never feed our own output back into the generator
    if START in css:
        css = css[:css.index(START)]
    rules = transform_block(css)
    return START + "\n" + MANUAL + "\n" + "\n".join(rules) + "\n" + END


def main() -> int:
    check = "--check" in sys.argv
    s = PAGE.read_text()
    block = build()
    if START in s:
        pre = s[:s.index(START)]
        post = s[s.index(END) + len(END):]
        new = pre + block + post
    else:
        b = s.index("</style>")
        new = s[:b] + block + "\n" + s[b:]
    if check:
        if new != s:
            print("STALE light theme: run scripts/build_light_theme.py")
            return 1
        print("OK: light theme current")
        return 0
    PAGE.write_text(new)
    print(f"Light theme written: {len(block)} chars, {block.count('{')} rules")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
